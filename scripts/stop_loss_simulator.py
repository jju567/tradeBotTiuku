"""
Trailing Stop-Loss Simulation Engine for Trade Execution Validation.

Simulates and backtests the execution of a 20% mechanical trailing stop-loss
on historical BUY signals generated by fundamental_backtester.py.
Compares unmanaged 6-month returns (Buy & Hold) vs. managed returns with trailing stop.
"""

