def main() -> None:
    parser = argparse.ArgumentParser(
        description="Stop-Loss Simulator: Test 2.5x ATR Dynamic Trailing Stop on fundamental buy signals."
    )
    parser.add_argument(
        "--signals",
        default="data/institutional_backtest_results.csv",
        help="Path to fundamental signals CSV file.",
    )
    parser.add_argument(
        "--atr-multiplier",
        type=float,
        default=2.5,
        help="ATR stop-loss multiplier (default: 2.5).",
    )
    parser.add_argument(
        "--atr-period",
        type=int,
        default=14,
        help="ATR rolling window period in trading days (default: 14).",
    )
    parser.add_argument(
        "--output",
        default="data/stop_loss_simulation_results.csv",
        help="Path to save trade simulation results CSV.",
    )

    args = parser.parse_args()

    simulator = StopLossSimulator(
        signals_csv=args.signals,
        atr_multiplier=args.atr_multiplier,
        atr_period=args.atr_period,
    )

    trades_df, summary_df = simulator.run()

    print("\n" + "=" * 90)
    print(f"🛡️ DYNAMIC ATR TRAILING STOP-LOSS REPORT ({args.atr_multiplier:.1f}x ATR, {args.atr_period}d)")
    print("=" * 90)

    if not summary_df.empty:
        print(summary_df.to_string(index=False))
    else:
        print("No simulation summary available.")

    print("\n" + "=" * 90)
    print("📋 SAMPLE DETAILED TRADES (FIRST 15)")
    print("=" * 90)

    if not trades_df.empty:
        display_cols = [
            "ticker", "buy_date", "buy_price", "unmanaged_return_pct",
            "managed_return_pct", "exit_type", "sell_date", "sell_price", "holding_days"
        ]
        print(trades_df[display_cols].head(15).to_string(index=False))

        # Save to CSV
        try:
            trades_df.to_csv(args.output, index=False)
            print(f"\nSaved {len(trades_df)} simulation records to {args.output}")
        except Exception as e:
            logger.error(f"Failed to save CSV to {args.output}: {e}")
    else:
        print("No trades simulated.")


if __name__ == "__main__":
    main()
